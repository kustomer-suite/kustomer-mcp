#!/usr/bin/env node
import { writeFileSync } from "node:fs";

import { type Fixture } from "../conformance/fake-api.js";
import { buildHardFixture } from "../eval/fixture-hard.js";
import { openAiEmbedder } from "../edge/embed.js";

// Writes the SQL that puts the synthetic store (the one the evaluation uses) into
// the sandbox schema. Two steps, so the part that needs no key needs none:
//   node dist/scripts/sandbox-seed.js data       > the conversations, messages, logs, passages, quota
//   OPENAI_API_KEY=... node dist/scripts/sandbox-seed.js embeddings   > the vectors, and the model they came from
// Both outputs are migrations: `supabase db push` applies them. The vectors are of
// made-up text, so committing them is fine, and committed they make the sandbox
// reproducible without anyone needing a key.

const lit = (s: string) => `'${s.replaceAll("'", "''")}'`;
const jsonb = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const uuid = (s: string, what: string) => {
  if (!UUID.test(s)) throw new Error(`${what} is not a uuid: ${s}`);
  return lit(s);
};

export function dataSql(fx: Fixture): string {
  const out: string[] = ["-- Generated by scripts/sandbox-seed.ts from the evaluation's fixture. Synthetic data. Do not edit by hand.", "begin;"];
  out.push("truncate sandbox.messages, sandbox.conversations, sandbox.tool_logs, sandbox.knowledge, sandbox.meta restart identity cascade;");
  out.push(`insert into sandbox.meta (key, value) values ('quota', ${jsonb(fx.quota)}), ('store', ${jsonb(fx.store)});`);

  const seen = new Set<string>();
  for (const c of fx.conversations as Array<Record<string, unknown> & { id: string; store_id: string; channel: string; handover_status: string; started_at: string; last_message_at?: string; messages: Array<Record<string, unknown> & { id: string }> }>) {
    const { messages, ...rest } = c;
    out.push(
      `insert into sandbox.conversations (id, store_id, channel, handover_status, started_at, activity, body) values (${uuid(c.id, "conversation id")}, ${uuid(c.store_id, "store id")}, ${lit(c.channel)}, ${lit(c.handover_status)}, ${lit(c.started_at)}, ${lit(c.last_message_at ?? c.started_at)}, ${jsonb(rest)});`,
    );
    messages.forEach((m, i) => {
      if (!m.id) throw new Error(`a message of ${c.id} has no id`);
      if (seen.has(m.id)) throw new Error(`message id ${m.id} is not unique`);
      seen.add(m.id);
      out.push(`insert into sandbox.messages (id, conversation_id, seq, body) values (${lit(m.id)}, ${uuid(c.id, "conversation id")}, ${i}, ${jsonb(m)});`);
    });
  }

  for (const l of fx.toolLogs as unknown as Array<Record<string, unknown> & { store_id: string; conversation_id?: string | null; tool_name: string; created_at: string }>) {
    const conv = l.conversation_id ? uuid(l.conversation_id, "tool log conversation id") : "null";
    out.push(`insert into sandbox.tool_logs (store_id, conversation_id, tool_name, created_at, body) values (${uuid(l.store_id, "store id")}, ${conv}, ${lit(l.tool_name)}, ${lit(l.created_at)}, ${jsonb(l)});`);
  }
  for (const k of fx.knowledge) {
    out.push(`insert into sandbox.knowledge (store_id, kb_item_id, title, chunk_text) values (${uuid(k.store_id, "store id")}, ${lit(k.kb_item_id)}, ${lit(k.title)}, ${lit(k.chunk_text)});`);
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}

export async function embeddingsSql(fx: Fixture, embed: (t: string) => Promise<number[]>, model: string): Promise<string> {
  const out: string[] = [`-- Generated by scripts/sandbox-seed.ts. Vectors of synthetic passages made with ${model}. Do not edit by hand.`, "begin;"];
  for (const k of fx.knowledge) {
    const v = await embed(`${k.title}\n${k.chunk_text}`);
    out.push(
      `update sandbox.knowledge set embedding = '[${v.join(",")}]'::extensions.vector where store_id = ${uuid(k.store_id, "store id")} and kb_item_id = ${lit(k.kb_item_id)} and chunk_text = ${lit(k.chunk_text)};`,
    );
  }
  out.push(`insert into sandbox.meta (key, value) values ('embedding_model', ${jsonb(model)}) on conflict (key) do update set value = excluded.value;`);
  out.push("commit;");
  return out.join("\n") + "\n";
}

// Only when run as a program, not when a test imports the functions above.
if (process.argv[1]?.endsWith("sandbox-seed.js")) {
  const mode = process.argv[2];
  const fx = buildHardFixture();
  const target = process.argv[3];
  const write = (sql: string) => (target ? writeFileSync(target, sql) : process.stdout.write(sql));
  if (mode === "data") write(dataSql(fx));
  else if (mode === "embeddings") {
    const key = process.env.OPENAI_API_KEY;
    if (!key) throw new Error("OPENAI_API_KEY is not set");
    const model = process.env.EMBEDDING_MODEL ?? "text-embedding-3-small";
    write(await embeddingsSql(fx, openAiEmbedder({ apiKey: key, model }), model));
  } else throw new Error("usage: sandbox-seed.js data|embeddings [output file]");
}


